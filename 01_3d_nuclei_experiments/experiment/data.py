"""Training data. Volumes are ALREADY normalized; never renormalize them here."""
import json
from pathlib import Path
import numpy as np
import tifffile
import torch
from torch.utils.data import Dataset


def list_cases(folder):
    folder = Path(folder)
    return sorted(d for d in folder.glob('*') if d.is_dir() and (d / 'nuclei_patch.tif').exists())


def load_case(path):
    path = Path(path)
    image = tifffile.imread(path / 'nuclei_patch.tif').astype(np.float32)
    labels = tifffile.imread(path / 'masks_patch.tif').astype(np.int32)
    with np.load(path / 'flow_patch.npz') as f:
        flow = np.asarray(f['arr_0'], dtype=np.float32)
    profile = np.asarray(np.load(path / 'profile.npy'), dtype=np.float32).reshape(-1)
    if image.ndim != 3 or labels.shape != image.shape or flow.shape != (3, *image.shape):
        raise ValueError(f'Invalid ZYX shapes in {path}: {image.shape}, {labels.shape}, {flow.shape}')
    if profile.shape != (8,):
        raise ValueError(f'Expected 8 intensity profile entries: {path}')
    if np.min(image) < 0 or not np.isfinite(image).all() or not np.isfinite(flow).all():
        raise ValueError(f'Nonfinite or negative intensities/flows: {path}')
    if not np.isfinite(profile).all():
        # Old datasets can contain nonfinite kurtosis; treat it as uninformative.
        profile = np.nan_to_num(profile, nan=0., posinf=0., neginf=0.)
    # Zero-intensity labels cannot be learned because those voxels are excluded.
    return {'image': image, 'labels': labels, 'flow': flow,
            'profile': profile, 'case_id': path.name, 'path': path}


def source_group(path):
    """Conservative default: patches generated by the same commit are kept together.

    Replace/verify this grouping with explicit specimen IDs in groups.json; a
    commit is only a safety heuristic and is NOT a biological sample identifier.
    """
    path = Path(path)
    custom = path.parent / 'groups.json'
    if custom.exists():
        mapping = json.loads(custom.read_text())
        if path.name in mapping:
            return str(mapping[path.name])
    md_file = path / 'MetaData.json'
    md = json.loads(md_file.read_text()).get('Example_MetaData', {}) if md_file.exists() else {}
    return md.get('source_specimen') or md.get('source_image') or ('unknown_commit_' + str(md.get('git hash', path.name)))


def make_splits(paths, seed=37):
    """Hold out WHOLE groups; no overlapping patches in different splits."""
    from collections import defaultdict
    groups = defaultdict(list)
    for p in paths:
        groups[source_group(p)].append(p)
    keys = sorted(groups)
    if len(keys) < 2:
        raise ValueError('Need at least two independent specimen groups for validation')
    rng = np.random.default_rng(seed)
    rng.shuffle(keys)
    n_val = max(1, int(round(0.2 * len(keys))))
    val_groups = set(keys[:n_val])
    train = [p for k in keys if k not in val_groups for p in groups[k]]
    val = [p for k in keys if k in val_groups for p in groups[k]]
    assert not set(source_group(p) for p in train) & set(source_group(p) for p in val)
    return train, val


def transform_zyx(image, labels, flow, features=None, k=0, flip_x=False, flip_z=False):
    """XY rotations, X flip, Z flip. Flow channels are [Z,Y,X].

    Cached pretrained features are transformed at their spatial grid resolution;
    intensity transforms are deliberately excluded.
    """
    k = int(k) % 4
    image = np.rot90(image, k, axes=(-2, -1))
    labels = np.rot90(labels, k, axes=(-2, -1))
    flow = np.rot90(flow, k, axes=(-2, -1)).copy()
    if features is not None:
        features = np.rot90(features, k, axes=(-2, -1))
    # One 90-degree CCW rotation in y,x: (dy,dx) -> (-dx,dy).
    for _ in range(k):
        vy, vx = flow[1].copy(), flow[2].copy()
        flow[1], flow[2] = -vx, vy
    if flip_x:
        image, labels, flow = np.flip(image, -1), np.flip(labels, -1), np.flip(flow, -1).copy()
        flow[2] *= -1
        if features is not None: features = np.flip(features, -1)
    if flip_z:
        image, labels, flow = np.flip(image, -3), np.flip(labels, -3), np.flip(flow, -3).copy()
        flow[0] *= -1
        if features is not None: features = np.flip(features, -3)
    return tuple(np.ascontiguousarray(x) if x is not None else None
                 for x in (image, labels, flow, features))


def load_features(feature_dir, model_name, case_id):
    if model_name not in ('N5_microsam_xy', 'N6_microsam_xyz', 'N7_cpdino_xy'):
        return None
    backbone = 'microsam' if 'microsam' in model_name else 'cpdino'
    filename = Path(feature_dir) / backbone / (case_id + '.npz')
    if not filename.exists():
        raise FileNotFoundError(f'Missing pretrained features: {filename}. Run 04_cache_foundation.py first.')
    with np.load(filename) as f:
        channels = ['xy'] if 'xyz' not in model_name else ['xy', 'xz', 'yz']
        if any(view not in f for view in channels):
            raise ValueError(f'{filename} lacks required views {channels}')
        arrays = [np.asarray(f[view], np.float32) for view in channels]
    if len({a.shape for a in arrays}) != 1:
        raise ValueError(f'Incompatible orientation feature sizes in {filename}')
    return np.mean(arrays, axis=0, dtype=np.float32)  # same pretrained encoder, share channels


class NucleiPatches(Dataset):
    def __init__(self, paths, train=False, feature_dir=None, model_name='', seed=37):
        self.paths = list(paths)
        self.train = train
        self.feature_dir = feature_dir
        self.model_name = model_name
        self.rng = np.random.default_rng(seed)
        self.cases = [load_case(p) for p in self.paths]
        self.features = [load_features(feature_dir, model_name, c['case_id']) for c in self.cases]

    def __len__(self): return len(self.cases)

    def __getitem__(self, i):
        c = self.cases[i]
        img, labels, flow = c['image'], c['labels'], c['flow']
        features = self.features[i]
        if self.train:
            img, labels, flow, features = transform_zyx(
                img, labels, flow, features,
                k=self.rng.integers(4), flip_x=bool(self.rng.integers(2)),
                flip_z=bool(self.rng.integers(2)))
        result = {
            'image': torch.from_numpy(np.ascontiguousarray(img[None])).float(),
            'labels': torch.from_numpy(np.ascontiguousarray(labels)).long(),
            'flow': torch.from_numpy(np.ascontiguousarray(flow)).float(),
            'profile': torch.from_numpy(c['profile']).float(),
            'case_id': c['case_id']}
        if features is not None:
            result['features'] = torch.from_numpy(np.ascontiguousarray(features)).float()
        return result
